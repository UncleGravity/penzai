                8'd123: begin mag_floor = {7'd0, sig[23:22]};    has_fraction = |sig[21:0]; end
                8'd124: begin mag_floor = {6'd0, sig[23:21]};    has_fraction = |sig[20:0]; end
                8'd125: begin mag_floor = {5'd0, sig[23:20]};    has_fraction = |sig[19:0]; end
                8'd126: begin mag_floor = {4'd0, sig[23:19]};    has_fraction = |sig[18:0]; end
                8'd127: begin mag_floor = {3'd0, sig[23:18]};    has_fraction = |sig[17:0]; end
                8'd128: begin mag_floor = {2'd0, sig[23:17]};    has_fraction = |sig[16:0]; end
                8'd129: begin mag_floor = {1'd0, sig[23:16]};    has_fraction = |sig[15:0]; end
                8'd130: begin mag_floor = sig[23:15];            has_fraction = |sig[14:0]; end
                default: begin mag_floor = 9'd0; has_fraction = |value[30:0]; end
            endcase
