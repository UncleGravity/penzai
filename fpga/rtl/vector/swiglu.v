// swiglu - scalar SwiGLU transform.
//
// The projection sink presents paired gate/up FP32 values in resident order. This
// leaf evaluates a 1/32-grid piecewise-linear SiLU over [-16,16), multiplies by UP,
// and preserves scalar order/TLAST. It deliberately does not contain a quantizer:
// shared_q8 owns the design's sole q8_pack4 instance.
//
// Interior approximation:
//   silu(g) ~= trunc_add(trunc_mul(g, slope[segment]), intercept[segment])
//   y        = trunc_mul(silu(g), up)
// Tails are exact guards in the chosen approximation: g <= -16 -> 0; g >= 16 -> g.
// The 1024 x 64 slope/intercept ROM is generated by
// fpga/build/generators/swiglu_lut.zig.
// Its committed FNV64 is checked by fpga/build/generators/swiglu_coeffs.zig.
//
// Status is per scalar and remains stable with out_valid under backpressure:
//   [0] gate or up was non-finite; both were replaced by zero
//   [1] the final truncating multiply reached its finite saturation code
// abort synchronously discards every partial, in-flight, and queued scalar.

