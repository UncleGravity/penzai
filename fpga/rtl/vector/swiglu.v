    always @(posedge clk) begin
        if (fifo_write_enable)
            fifo_mem[fifo_write_ptr] <= result_payload;
    end

    // The payload register deliberately has no reset: only out_valid defines its
    // observability, and a resettable read register blocks RAMB18 inference.
    always @(posedge clk) begin
        if (fifo_read_enable) begin
`ifdef FORMAL
            fifo_read_data <= formal_fifo_read_payload;
`else
            fifo_read_data <= fifo_mem[fifo_read_ptr];
`endif
        end
    end

    always @(posedge clk) begin
        if (!rst_n || abort) begin
            out_valid <= 1'b0;
        end else if (fifo_read_enable) begin
            out_valid <= 1'b1;
        end else if (output_pop) begin
            out_valid <= 1'b0;
        end
    end

    always @(posedge clk) begin
        if (!rst_n || abort) begin
            reserved_count <= 7'd0;
        end else begin
            case ({input_accept, output_pop})
                2'b10: reserved_count <= reserved_count + 7'd1;
                2'b01: reserved_count <= reserved_count - 7'd1;
                default: reserved_count <= reserved_count;
            endcase
        end
    end

    always @(posedge clk) begin
        if (!rst_n || abort) begin
            fifo_read_ptr <= {FIFO_PTR_W{1'b0}};
            fifo_write_ptr <= {FIFO_PTR_W{1'b0}};
            fifo_count <= {(FIFO_PTR_W+1){1'b0}};
        end else begin
            if (fifo_write_enable)
                fifo_write_ptr <= fifo_write_ptr + 1'b1;
            if (fifo_read_enable)
                fifo_read_ptr <= fifo_read_ptr + 1'b1;
            case ({fifo_write_enable, fifo_read_enable})
                2'b10: fifo_count <= fifo_count + 1'b1;
                2'b01: fifo_count <= fifo_count - 1'b1;
                default: fifo_count <= fifo_count;
            endcase
        end
    end
